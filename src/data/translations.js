export function translateDiscovery(str, lang) {
  if (!str || str === "—") return str;
  if (lang !== "zh") return str;

  const countryMap = {
    "Sweden": "瑞典",
    "United Kingdom": "英国",
    "Great Britain": "英国",
    "France": "法国",
    "Germany": "德国",
    "United States": "美国",
    "Russia": "俄罗斯",
    "Soviet Union": "苏联",
    "Italy": "意大利",
    "Denmark": "丹麦",
    "Spain": "西班牙",
    "Greece": "希腊",
    "India": "印度",
    "China": "中国",
    "Ancient": "史前/古代发现",
    "Prehistoric": "史前时期"
  };

  const match = str.match(/(\d{3,4})\s+in\s+([A-Za-z\s]+)/i);
  if (match) {
    const year = match[1];
    const country = match[2].trim();
    const countryZh = countryMap[country] || country;
    return `${year}年 ${countryZh}`;
  }

  let res = str;
  for (const [en, zh] of Object.entries(countryMap)) {
    res = res.replace(new RegExp(en, "gi"), zh);
  }
  return res.replace(/\bin\b/gi, "").trim();
}

export function formatPropertyValue(val, lang) {
  if (val == null || val === "" || val === "N/A" || val === "None" || val === "—") {
    return "—";
  }
  let str = String(val).trim();

  // 1. Clean orphan closing HTML tags (like </a> leftover in Isotopic Abundances)
  str = str.replace(/<\/?a[^>]*>/gi, "");

  // 2. Normalize abnormal linebreaks and underscores in space groups
  str = str.replace(/_\s*\n\s*/g, " ");

  // 3. Comprehensive scientific and Greek HTML entities decoding
  str = str
    .replace(/&#8486;|&Omega;|&#937;/g, "Ω")
    .replace(/&times;/g, "×")
    .replace(/&middot;/g, "·")
    .replace(/&plusmn;/g, "±")
    .replace(/&minus;/g, "−")
    .replace(/&deg;C/g, "°C")
    .replace(/&deg;/g, "°")
    .replace(/&pi;/g, "π")
    .replace(/&mu;|&#956;/g, "μ")
    .replace(/&alpha;/g, "α")
    .replace(/&beta;/g, "β")
    .replace(/&gamma;/g, "γ")
    .replace(/&Delta;/g, "Δ")
    .replace(/&kappa;/g, "κ")
    .replace(/&lambda;/g, "λ")
    .replace(/&sigma;/g, "σ")
    .replace(/&thinsp;|&ensp;|&emsp;/g, " ");

  // 4. Eliminate floating-point precision glitches (e.g., 9.700000000001 -> 9.7)
  str = str.replace(/(\d+\.\d*?)000000000\d+/g, (match, prefix) => {
    return parseFloat(prefix).toString();
  });

  // 5. Wrap isotope tokens in atomic non-breaking spans so line wraps never break a superscript from its symbol
  if (str.includes("<sup>") && str.includes(",")) {
    const tokens = str.split(/,\s*/);
    if (tokens.length > 1 && tokens.every(t => t.includes("<sup>") || /^[A-Z][a-z]?$/i.test(t.trim()))) {
      return tokens.map(t => `<span class="isotope-chip">${t.trim()}</span>`).join('<span class="isotope-sep">, </span>');
    }
  }

  if (lang === "zh") {
    if (valueDict.zh[str]) {
      return valueDict.zh[str];
    }
  }

  return str;
}



